            await self.github.create_branch(target.repo_owner, target.repo_name, branch_name, target.default_branch)
            
            # 3. Inject files based on type
            files_created = []
            
            if target.injection_type == "python_package":
                for path in target.injection_paths:
                    await self._inject_python_package(target, path, branch_name)
                    files_created.append(path)
            
            elif target.injection_type == "typescript_package":
                for path in target.injection_paths:
                    await self._inject_typescript_package(target, path, branch_name)
                    files_created.append(path)
            
