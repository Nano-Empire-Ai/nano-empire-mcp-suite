class GitHubClient:
    def __init__(self, token: str, username: str):
        self.token = token
        self.username = username
        self.base_url = "https://api.github.com"
        self.headers = {
            "Authorization": f"token {token}",
            "Accept": "application/vnd.github.v3+json",
            "User-Agent": "VonNeumannReplicator/1.0"
        }
    
    async def fork_repo(self, owner: str, repo: str) -> Dict:
        """Fork a repository."""
        import httpx
        async with httpx.AsyncClient() as client:
            resp = await client.post(
                f"https://api.github.com/repos/{owner}/{repo}/forks",
                headers={"Authorization": f"token {self.token}", "Accept": "application/vnd.github.v3+json"},
                timeout=30.0
            )
            resp.raise_for_status()
            return resp.json()
    
    async def create_branch(self, owner: str, repo: str, branch: str, from_branch: str) -> bool:
        """Create a new branch from base branch."""
        import httpx
        async with httpx.AsyncClient() as client:
            # Get base branch SHA
            resp = await client.get(
                f"https://api.github.com/repos/{self.username}/{repo}/git/ref/heads/{branch}",
                headers=self.headers
            )
            if resp.status_code == 200:
                return True  # Branch exists
            
            # Get base branch SHA
            base_resp = await client.get(
                f"https://api.github.com/repos/{self.username}/{repo}/git/ref/heads/main",
                headers=self.headers
            )
            if base_resp.status_code != 200:
                base_resp = await client.get(
                    f"https://api.github.com/repos/{self.username}/{repo}/git/ref/heads/master",
                    headers=self.headers
                )
            
            sha = base_resp.json()["object"]["sha"]
            
            # Create new branch
            resp = await client.post(
                f"https://api.github.com/repos/{self.username}/{repo}/git/refs",
                headers=self.headers,
                json={"ref": f"refs/heads/{branch}", "sha": sha}
            )
            return resp.status_code == 201
    
    async def create_file(self, owner: str, repo: str, path: str, content: str, message: str, branch: str) -> bool:
        """Create or update a file."""
        import httpx
        import base64
        async with httpx.AsyncClient() as client:
            resp = await client.put(
                f"https://api.github.com/repos/{self.username}/{repo}/contents/{path}",
                headers=self.headers,
                json={
                    "message": message,
                    "content": base64.b64encode(content.encode()).decode(),
                    "branch": branch
                }
            )
            return resp.status_code in (200, 201)
    
    async def create_pull_request(self, owner: str, repo: str, title: str, body: str, head: str, base: str) -> Dict:
        """Create a pull request."""
        import httpx
        async with httpx.AsyncClient() as client:
            resp = await client.post(
                f"https://api.github.com/repos/{owner}/{repo}/pulls",
                headers=self.headers,
                json={
                    "title": title,
                    "body": body,
                    "head": f"{self.username}:{head}",
                    "base": "main"
                }
            )
            return resp.json()

