    if not GITHUB_TOKENS:
        logging.warning("Running in simulation mode. No PRs will be executed.")
        return
        
    # We still need a base client just to search for repos (read-only)
    base_g = Github(get_next_identity())
    keyword = random.choice(TARGET_KEYWORDS)
    targets = search_target_repos(base_g, keyword)
    
    for repo in targets:
        # Rotate identity per attempt to avoid rate limits / spam bans
        active_token = get_next_identity()
        worker_g = Github(active_token)
        execute_fork_and_pr(worker_g, repo)
        time.sleep(15) # Rate limit protection

